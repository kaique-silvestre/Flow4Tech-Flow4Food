-- Dominio do salao, ticket 07: cash payments of a comanda (immutable) and the cash received in a shift.
--   turnos_caixa.recebido_dinheiro_centavos  running total of the cash APPLIED to comandas while the shift is open (the change given back is not here). Pagamentos adds to it through the public contract of
--                                            Caixa; closing the shift computes `esperado = fundo + recebido` in SQL, so a payment racing the close is never missed.
--   pagamentos                               one row per payment, written once: the app credential has only SELECT and INSERT (a correction is a refund, outside this slice). id is generated by the client
--                                            (a repeat is never a second payment). recebido = aplicado + troco. turno_id is null when the unit does not require an open shift. saldo_apos and comanda_versao
--                                            are stored so a repeat answers with the very same response.
ALTER TABLE turnos_caixa ADD COLUMN recebido_dinheiro_centavos bigint NOT NULL DEFAULT 0 CHECK (recebido_dinheiro_centavos >= 0);

CREATE TABLE pagamentos (
  id               uuid PRIMARY KEY,
  organizacao_id   uuid        NOT NULL REFERENCES organizacoes (id),
  unidade_id       uuid        NOT NULL,
  comanda_id       uuid        NOT NULL,
  turno_id         uuid,
  metodo           text        NOT NULL CHECK (metodo = 'dinheiro'),
  recebido_centavos bigint     NOT NULL CHECK (recebido_centavos >= 1),
  aplicado_centavos bigint     NOT NULL CHECK (aplicado_centavos >= 1),
  troco_centavos   bigint      NOT NULL CHECK (troco_centavos >= 0),
  operador_id      uuid        NOT NULL,
  registrado_em    timestamptz NOT NULL,
  saldo_apos_centavos bigint   NOT NULL CHECK (saldo_apos_centavos >= 0),
  comanda_versao   integer     NOT NULL CHECK (comanda_versao >= 2),
  UNIQUE (organizacao_id, id),
  CHECK (recebido_centavos = aplicado_centavos + troco_centavos),
  FOREIGN KEY (organizacao_id, unidade_id) REFERENCES unidades (organizacao_id, id),
  FOREIGN KEY (organizacao_id, comanda_id) REFERENCES comandas (organizacao_id, id),
  FOREIGN KEY (organizacao_id, turno_id) REFERENCES turnos_caixa (organizacao_id, id),
  FOREIGN KEY (organizacao_id, operador_id) REFERENCES contas (organizacao_id, id)
);

CREATE INDEX pagamentos_por_comanda ON pagamentos (organizacao_id, comanda_id, registrado_em);
CREATE INDEX pagamentos_por_turno ON pagamentos (organizacao_id, turno_id) WHERE turno_id IS NOT NULL;

ALTER TABLE pagamentos ENABLE ROW LEVEL SECURITY;
ALTER TABLE pagamentos FORCE  ROW LEVEL SECURITY;
CREATE POLICY isolamento ON pagamentos
  USING (organizacao_id = (SELECT app_organizacao_id()))
  WITH CHECK (organizacao_id = (SELECT app_organizacao_id()));

REVOKE UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER ON pagamentos FROM flow4tech_app;
REVOKE ALL ON pagamentos FROM PUBLIC;
