/// <summary>
/// The menu on PostgreSQL. Joins the caller's unit of work (<see cref="TenantUnitOfWork.Require"/>); never filters on <c>organizacao_id</c> (RLS does). Updates are conditional on the
/// stored version, so two editors cannot overwrite each other.
/// </summary>
public sealed class PostgresCardapioStore : ICardapioStore
{
    public async Task<IReadOnlyList<Categoria>> ListarCategoriasAsync(Guid organizationId, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        return await context.Categorias.AsNoTracking().OrderBy(c => c.Nome).Select(c => new Categoria(c.Id, c.Nome, c.Ativa, c.Versao, c.CategoriaPaiId)).ToListAsync(cancellationToken);
    }

    public async Task<Categoria?> AcharCategoriaAsync(Guid organizationId, Guid id, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        return await context.Categorias.AsNoTracking().Where(c => c.Id == id).Select(c => new Categoria(c.Id, c.Nome, c.Ativa, c.Versao, c.CategoriaPaiId)).FirstOrDefaultAsync(cancellationToken);
    }

    public async Task InserirCategoriaAsync(Guid organizationId, Categoria categoria, DateTimeOffset now, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(categoria);
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        context.Categorias.Add(new CategoriaRow { Id = categoria.Id, OrganizacaoId = organizationId, Nome = categoria.Nome, Ativa = categoria.Ativa, Versao = categoria.Versao, CategoriaPaiId = categoria.CategoriaPaiId, CriadaEm = now, AtualizadaEm = now });
        await context.SaveChangesAsync(cancellationToken);
    }

    public async Task<bool> AlterarCategoriaAsync(Guid organizationId, Categoria nova, int versaoEsperada, DateTimeOffset now, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(nova);
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var rows = await context.Categorias
            .Where(c => c.Id == nova.Id && c.Versao == versaoEsperada)
            .ExecuteUpdateAsync(s => s.SetProperty(c => c.Nome, nova.Nome).SetProperty(c => c.Ativa, nova.Ativa).SetProperty(c => c.Versao, nova.Versao).SetProperty(c => c.CategoriaPaiId, nova.CategoriaPaiId).SetProperty(c => c.AtualizadaEm, now), cancellationToken);
        return rows == 1;
    }

    public async Task<bool> TemSubcategoriasAsync(Guid organizationId, Guid id, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        return await context.Categorias.AsNoTracking().AnyAsync(c => c.CategoriaPaiId == id, cancellationToken);
    }

    public async Task<bool> NomeEmUsoAsync(Guid organizationId, string nome, Guid? exceto, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        return await context.Categorias.AsNoTracking().AnyAsync(c => c.Nome == nome && c.Id != exceto, cancellationToken);
    }

    public async Task<IReadOnlyList<Produto>> ListarProdutosAsync(Guid organizationId, Guid unitId, bool incluirInativos, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var rows = await context.Produtos.AsNoTracking().Where(p => incluirInativos || p.Ativo).OrderBy(p => p.Nome).ThenBy(p => p.Codigo).Select(p => new { Row = p, Unidade = context.PrecosDaUnidade.Where(u => u.UnidadeId == unitId && u.ProdutoId == p.Id).Select(u => (long?)u.PrecoCentavos).FirstOrDefault() }).ToListAsync(cancellationToken);
        return [.. rows.Select(x => Mapa(x.Row, x.Unidade))];
    }

    public async Task<IReadOnlyList<Produto>> BuscarProdutosAsync(Guid organizationId, Guid unitId, string termoNormalizado, string codigo, int limite, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var rows = await Busca(context, unitId, termoNormalizado, codigo, limite).ToListAsync(cancellationToken);
        return [.. rows.Select(x => Mapa(x.Row, x.Unidade))];
    }

    /// <summary>The search query (one statement, unit price as a subselect), exposed so a test can assert its SQL text.</summary>
    internal static IQueryable<ProdutoComPrecoDaUnidade> Busca(CardapioDbContext context, Guid unitId, string termoNormalizado, string codigo, int limite) =>
        context.Produtos.AsNoTracking()
            .Where(p => p.Ativo && (p.Codigo == codigo || p.NomeBusca.Contains(termoNormalizado)))
            .OrderBy(p => p.Codigo == codigo ? 0 : p.NomeBusca.StartsWith(termoNormalizado) ? 1 : 2).ThenBy(p => p.Nome).ThenBy(p => p.Codigo)
            .Take(limite)
            .Select(p => new ProdutoComPrecoDaUnidade(p, context.PrecosDaUnidade.Where(u => u.UnidadeId == unitId && u.ProdutoId == p.Id).Select(u => (long?)u.PrecoCentavos).FirstOrDefault()));

    public async Task<IReadOnlyList<Produto>> FavoritosAsync(Guid organizationId, Guid unitId, Guid garcomId, int limite, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var rows = await context.FrequenciaDoGarcom.AsNoTracking()
            .Where(f => f.UnidadeId == unitId && f.GarcomId == garcomId && f.Lancamentos > 0)
            .Join(context.Produtos.AsNoTracking().Where(p => p.Ativo), f => f.ProdutoId, p => p.Id, (f, p) => new { f.Lancamentos, Produto = p })
            .OrderByDescending(x => x.Lancamentos).ThenBy(x => x.Produto.Nome).ThenBy(x => x.Produto.Id)
            .Take(limite)
            .Select(x => new { Row = x.Produto, Unidade = context.PrecosDaUnidade.Where(u => u.UnidadeId == unitId && u.ProdutoId == x.Produto.Id).Select(u => (long?)u.PrecoCentavos).FirstOrDefault() })
            .ToListAsync(cancellationToken);
        return [.. rows.Select(x => Mapa(x.Row, x.Unidade))];
    }

    public async Task<IReadOnlyList<Produto>> FrequentesAsync(Guid organizationId, Guid unitId, int limite, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var rows = await context.Frequencia.AsNoTracking()
            .Where(f => f.UnidadeId == unitId && f.Lancamentos > 0)
            .Join(context.Produtos.AsNoTracking().Where(p => p.Ativo), f => f.ProdutoId, p => p.Id, (f, p) => new { f.Lancamentos, Produto = p })
            .OrderByDescending(x => x.Lancamentos).ThenBy(x => x.Produto.Nome)
            .Take(limite)
            .Select(x => new { Row = x.Produto, Unidade = context.PrecosDaUnidade.Where(u => u.UnidadeId == unitId && u.ProdutoId == x.Produto.Id).Select(u => (long?)u.PrecoCentavos).FirstOrDefault() })
            .ToListAsync(cancellationToken);
        return [.. rows.Select(x => Mapa(x.Row, x.Unidade))];
    }

    public async Task<Produto?> AcharProdutoAsync(Guid organizationId, Guid unitId, Guid id, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var found = await context.Produtos.AsNoTracking().Where(p => p.Id == id).Select(p => new { Row = p, Unidade = context.PrecosDaUnidade.Where(u => u.UnidadeId == unitId && u.ProdutoId == p.Id).Select(u => (long?)u.PrecoCentavos).FirstOrDefault() }).FirstOrDefaultAsync(cancellationToken);
        return found is null ? null : Mapa(found.Row, found.Unidade);
    }

    public async Task<bool> CodigoEmUsoAsync(Guid organizationId, string codigo, Guid? exceto, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        return await context.Produtos.AsNoTracking().AnyAsync(p => p.Codigo == codigo && p.Id != exceto, cancellationToken);
    }

    public async Task InserirProdutoAsync(Guid organizationId, Produto produto, DateTimeOffset now, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(produto);
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        context.Produtos.Add(new ProdutoRow
        {
            Id = produto.Id,
            OrganizacaoId = organizationId,
            CategoriaId = produto.CategoriaId,
            Codigo = produto.Codigo,
            Nome = produto.Nome,
            PrecoCentavos = produto.PrecoCentavos,
            Moeda = produto.Moeda,
            Ativo = produto.Ativo,
            Indisponivel = produto.Indisponivel,
            PrecoPromocionalCentavos = produto.Promocao?.PrecoCentavos,
            PromocaoInicio = produto.Promocao?.Inicio,
            PromocaoFim = produto.Promocao?.Fim,
            Versao = produto.Versao,
            CriadoEm = now,
            AtualizadoEm = now,
        });
        await context.SaveChangesAsync(cancellationToken);
    }

    public async Task<bool> AlterarProdutoAsync(Guid organizationId, Produto novo, int versaoEsperada, DateTimeOffset now, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(novo);
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var rows = await context.Produtos
            .Where(p => p.Id == novo.Id && p.Versao == versaoEsperada)
            .ExecuteUpdateAsync(
                s => s.SetProperty(p => p.CategoriaId, novo.CategoriaId).SetProperty(p => p.Codigo, novo.Codigo).SetProperty(p => p.Nome, novo.Nome)
                    .SetProperty(p => p.PrecoCentavos, novo.PrecoCentavos).SetProperty(p => p.Ativo, novo.Ativo)
                    .SetProperty(p => p.Indisponivel, novo.Indisponivel).SetProperty(p => p.PrecoPromocionalCentavos, novo.Promocao == null ? null : novo.Promocao.PrecoCentavos)
                    .SetProperty(p => p.PromocaoInicio, novo.Promocao == null ? null : novo.Promocao.Inicio).SetProperty(p => p.PromocaoFim, novo.Promocao == null ? null : novo.Promocao.Fim).SetProperty(p => p.Versao, novo.Versao).SetProperty(p => p.AtualizadoEm, now),
                cancellationToken);
        return rows == 1;
    }

    public async Task DefinirPrecoDaUnidadeAsync(Guid organizationId, Guid unitId, Guid produtoId, long precoCentavos, DateTimeOffset now, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        await context.Database.ExecuteSqlInterpolatedAsync(
            $"""
            INSERT INTO produtos_preco_unidade (organizacao_id, unidade_id, produto_id, preco_centavos, atualizado_em)
            VALUES ({organizationId}, {unitId}, {produtoId}, {precoCentavos}, {now})
            ON CONFLICT (organizacao_id, unidade_id, produto_id) DO UPDATE SET preco_centavos = EXCLUDED.preco_centavos, atualizado_em = EXCLUDED.atualizado_em
            """,
            cancellationToken);
    }

    public async Task<bool> RemoverPrecoDaUnidadeAsync(Guid organizationId, Guid unitId, Guid produtoId, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        return await context.PrecosDaUnidade.Where(x => x.UnidadeId == unitId && x.ProdutoId == produtoId).ExecuteDeleteAsync(cancellationToken) == 1;
    }

    private static Produto Mapa(ProdutoRow p, long? unidade) => new(
        p.Id,
        p.CategoriaId,
        p.Codigo,
        p.Nome,
        p.PrecoCentavos,
        p.Moeda,
        p.Ativo,
        p.Versao,
        p.Indisponivel,
        p.PrecoPromocionalCentavos is { } preco && p.PromocaoInicio is { } inicio && p.PromocaoFim is { } fim ? new Promocao(preco, inicio, fim) : null,
        unidade);
}

/// <summary>Option groups on PostgreSQL. Joins the caller's unit of work; never filters on <c>organizacao_id</c> (RLS does). The group update is conditional on the stored version.</summary>
public sealed class PostgresOpcoesStore : IOpcoesStore
{
    public async Task<IReadOnlyList<GrupoDeOpcao>> ListarGruposAsync(Guid organizationId, bool incluirInativos, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var grupos = await context.Grupos.AsNoTracking().Where(g => incluirInativos || g.Ativo).OrderBy(g => g.Nome).ThenBy(g => g.Id).ToListAsync(cancellationToken);
        var opcoes = await context.Opcoes.AsNoTracking().OrderBy(o => o.Posicao).ToListAsync(cancellationToken);
        return grupos.Select(g => Mapa(g, opcoes.Where(o => o.GrupoId == g.Id))).ToList();
    }

    public async Task<GrupoDeOpcao?> AcharGrupoAsync(Guid organizationId, Guid id, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var grupo = await context.Grupos.AsNoTracking().Where(g => g.Id == id).FirstOrDefaultAsync(cancellationToken);
        if (grupo is null)
        {
            return null;
        }

        var opcoes = await context.Opcoes.AsNoTracking().Where(o => o.GrupoId == id).OrderBy(o => o.Posicao).ToListAsync(cancellationToken);
        return Mapa(grupo, opcoes);
    }

    public async Task<IReadOnlyList<GrupoDeOpcao>> GruposDoProdutoAsync(Guid organizationId, Guid produtoId, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var vinculos = await context.ProdutoGrupos.AsNoTracking().Where(v => v.ProdutoId == produtoId).OrderBy(v => v.Posicao).ToListAsync(cancellationToken);
        var ids = vinculos.Select(v => v.GrupoId).ToList();
        var grupos = await context.Grupos.AsNoTracking().Where(g => ids.Contains(g.Id)).ToListAsync(cancellationToken);
        var opcoes = await context.Opcoes.AsNoTracking().Where(o => ids.Contains(o.GrupoId)).OrderBy(o => o.Posicao).ToListAsync(cancellationToken);
        return vinculos.Select(v => Mapa(grupos.Single(g => g.Id == v.GrupoId), opcoes.Where(o => o.GrupoId == v.GrupoId))).ToList();
    }

    public async Task InserirGrupoAsync(Guid organizationId, GrupoDeOpcao grupo, DateTimeOffset now, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(grupo);
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        context.Grupos.Add(new GrupoOpcaoRow { Id = grupo.Id, OrganizacaoId = organizationId, Nome = grupo.Nome, Minimo = grupo.Minimo, Maximo = grupo.Maximo, Ativo = grupo.Ativo, Versao = grupo.Versao, CriadoEm = now, AtualizadoEm = now });
        await context.SaveChangesAsync(cancellationToken);
        await GravarOpcoesAsync(context, organizationId, grupo, cancellationToken);
    }

    public async Task<bool> AlterarGrupoAsync(Guid organizationId, GrupoDeOpcao novo, int versaoEsperada, DateTimeOffset now, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(novo);
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var rows = await context.Grupos
            .Where(g => g.Id == novo.Id && g.Versao == versaoEsperada)
            .ExecuteUpdateAsync(s => s.SetProperty(g => g.Nome, novo.Nome).SetProperty(g => g.Minimo, novo.Minimo).SetProperty(g => g.Maximo, novo.Maximo).SetProperty(g => g.Ativo, novo.Ativo).SetProperty(g => g.Versao, novo.Versao).SetProperty(g => g.AtualizadoEm, now), cancellationToken);
        if (rows != 1)
        {
            return false;
        }

        await GravarOpcoesAsync(context, organizationId, novo, cancellationToken);
        return true;
    }

    public async Task<int> ContarGruposAsync(Guid organizationId, IReadOnlyCollection<Guid> ids, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(ids);
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var lista = ids.ToList();
        return await context.Grupos.AsNoTracking().CountAsync(g => lista.Contains(g.Id), cancellationToken);
    }

    public async Task<IReadOnlyDictionary<Guid, IReadOnlyList<Guid>>> VinculosDosProdutosAsync(Guid organizationId, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var vinculos = await context.ProdutoGrupos.AsNoTracking().OrderBy(v => v.Posicao).ToListAsync(cancellationToken);
        return vinculos.GroupBy(v => v.ProdutoId).ToDictionary(g => g.Key, g => (IReadOnlyList<Guid>)[.. g.Select(v => v.GrupoId)]);
    }

    public async Task DefinirGruposDoProdutoAsync(Guid organizationId, Guid produtoId, IReadOnlyList<Guid> grupoIds, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(grupoIds);
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        await context.ProdutoGrupos.Where(v => v.ProdutoId == produtoId).ExecuteDeleteAsync(cancellationToken);
        for (var i = 0; i < grupoIds.Count; i++)
        {
            context.ProdutoGrupos.Add(new ProdutoGrupoOpcaoRow { OrganizacaoId = organizationId, ProdutoId = produtoId, GrupoId = grupoIds[i], Posicao = i + 1 });
        }

        await context.SaveChangesAsync(cancellationToken);
    }

    public async Task<IReadOnlyList<OpcaoFrequente>> FrequentesAsync(Guid organizationId, Guid unitId, Guid produtoId, int limite, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var rows = await context.OpcoesFrequencia.AsNoTracking()
            .Where(f => f.UnidadeId == unitId && f.ProdutoId == produtoId)
            .Join(context.Opcoes.AsNoTracking().Where(o => o.Ativa), f => f.OpcaoId, o => o.Id, (f, o) => new { f.Lancamentos, Opcao = o })
            .Join(context.Grupos.AsNoTracking().Where(g => g.Ativo), x => x.Opcao.GrupoId, g => g.Id, (x, g) => new { x.Lancamentos, x.Opcao, GrupoNome = g.Nome })
            .OrderByDescending(x => x.Lancamentos).ThenBy(x => x.Opcao.Nome).ThenBy(x => x.Opcao.Id)
            .Take(limite)
            .ToListAsync(cancellationToken);
        return rows.Select(x => new OpcaoFrequente(x.Opcao.GrupoId, x.GrupoNome, new Opcao(x.Opcao.Id, x.Opcao.Nome, x.Opcao.PrecoCentavos, x.Opcao.Ativa), x.Lancamentos)).ToList();
    }

    private static async Task GravarOpcoesAsync(CardapioDbContext context, Guid organizationId, GrupoDeOpcao grupo, CancellationToken cancellationToken)
    {
        for (var i = 0; i < grupo.Opcoes.Count; i++)
        {
            var o = grupo.Opcoes[i];
            await context.Database.ExecuteSqlInterpolatedAsync(
                $"""
                INSERT INTO opcoes (id, organizacao_id, grupo_id, nome, preco_centavos, ativa, posicao)
                VALUES ({o.Id}, {organizationId}, {grupo.Id}, {o.Nome}, {o.PrecoCentavos}, {o.Ativa}, {i + 1})
                ON CONFLICT (id) DO UPDATE SET nome = EXCLUDED.nome, preco_centavos = EXCLUDED.preco_centavos, ativa = EXCLUDED.ativa, posicao = EXCLUDED.posicao
                WHERE opcoes.grupo_id = EXCLUDED.grupo_id
                """,
                cancellationToken);
        }
    }

    private static GrupoDeOpcao Mapa(GrupoOpcaoRow g, IEnumerable<OpcaoRow> opcoes) =>
        new(g.Id, g.Nome, g.Minimo, g.Maximo, g.Ativo, g.Versao, opcoes.OrderBy(o => o.Posicao).Select(o => new Opcao(o.Id, o.Nome, o.PrecoCentavos, o.Ativa)).ToList());
}

/// <summary>The record of applied imports on PostgreSQL: append-only (the application credential has SELECT and INSERT), one row per import id.</summary>
public sealed class PostgresImportacoesStore : IImportacoesDoCardapioStore
{
    public async Task<ImportacaoRegistrada?> AcharAsync(Guid organizationId, Guid id, CancellationToken cancellationToken)
    {
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var r = await context.Importacoes.AsNoTracking().Where(x => x.Id == id).FirstOrDefaultAsync(cancellationToken);
        return r is null
            ? null
            : new ImportacaoRegistrada(r.Id, r.ConteudoSha256, new ResumoDaImportacao(r.CategoriasCriadas, r.CategoriasAtualizadas, r.ProdutosCriados, r.ProdutosAtualizados, r.GruposCriados, r.GruposAtualizados, r.OpcoesCriadas, r.OpcoesAtualizadas), r.CriadoPor, r.CriadoEm);
    }

    public async Task<bool> RegistrarAsync(Guid organizationId, ImportacaoRegistrada importacao, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(importacao);
        var r = importacao.Resumo;
        await using var context = new CardapioDbContext(TenantUnitOfWork.Require(organizationId));
        var linhas = await context.Database.ExecuteSqlInterpolatedAsync(
            $"""
            INSERT INTO importacoes_cardapio (id, organizacao_id, conteudo_sha256, categorias_criadas, categorias_atualizadas, produtos_criados, produtos_atualizados, grupos_criados, grupos_atualizados, opcoes_criadas, opcoes_atualizadas, criado_por, criado_em)
            VALUES ({importacao.Id}, {organizationId}, {importacao.Hash}, {r.CategoriasCriadas}, {r.CategoriasAtualizadas}, {r.ProdutosCriados}, {r.ProdutosAtualizados}, {r.GruposCriados}, {r.GruposAtualizados}, {r.OpcoesCriadas}, {r.OpcoesAtualizadas}, {importacao.CriadoPor}, {importacao.CriadoEm})
            ON CONFLICT (organizacao_id, id) DO NOTHING
            """,
            cancellationToken);
        return linhas == 1;
    }
}

/// <summary>Menu events through the outbox, on the unit of work in progress (they commit or roll back with the change that raised them).</summary>
public sealed class OutboxEventosDoCardapio(OutboxWriter outbox) : IEventosDoCardapio
{
    public Task PublicarAsync(OrganizationContext organization, IDomainEvent evento, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(organization);
        return outbox.AddAsync(TenantUnitOfWork.Require(organization.OrganizationId), organization, evento, cancellationToken);
    }
}

public static class CardapioServices
{
    /// <summary>Registers the menu module. Needs <c>AddTenantData</c>, <c>AddAuditoria</c> (audit log) and <c>IClock</c>.</summary>
    public static IServiceCollection AddCardapio(this IServiceCollection services)
    {
        ArgumentNullException.ThrowIfNull(services);
        services.TryAddSingleton<OutboxWriter>();
        services.AddSingleton<ICardapioStore, PostgresCardapioStore>();
        services.AddSingleton<IEventosDoCardapio, OutboxEventosDoCardapio>();
        services.AddSingleton<GestaoDoCardapio>();
        services.AddSingleton<IOpcoesStore, PostgresOpcoesStore>();
        services.AddSingleton<GestaoDeOpcoes>();
        services.AddSingleton<IImportacoesDoCardapioStore, PostgresImportacoesStore>();
        services.AddSingleton<ILeitorDePlanilha, LeitorDePlanilha>();
        services.AddSingleton<GestaoDaImportacao>();
        return services;
    }
}
