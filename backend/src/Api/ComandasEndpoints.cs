using Flow4Tech.Comandas.Application;
using Flow4Tech.Comandas.Domain;

namespace Flow4Tech.Api;

internal sealed record ComandaDto(
    Guid Id,
    Guid UnidadeId,
    int Numero,
    string NumeroTexto,
    string Identificacao,
    Guid? MesaId,
    string Canal,
    Guid GarcomId,
    int? Pessoas,
    string Estado,
    decimal TaxaServicoPercentual,
    bool TaxaServicoRemovida,
    int Versao,
    DateTimeOffset AbertaEm);

/// <summary>Every field is optional on purpose: a comanda opens with a number only. Unit, waiter and channel never come from the body.</summary>
internal sealed record AbrirComandaRequest(string? Identificacao, Guid? MesaId, int? Pessoas);

internal sealed record ItemDto(Guid Id, Guid RodadaId, int Posicao, Guid ProdutoId, string ProdutoNome, long PrecoCentavos, int Quantidade, string? Observacao, string Estado, string? MotivoCancelamento, Guid? CanceladoPor, DateTimeOffset? CanceladoEm);

/// <summary><c>ComandaVersao</c> is the comanda version after the write: the one the client sends with its next write.</summary>
internal sealed record RodadaDto(Guid Id, Guid ComandaId, DateTimeOffset EnviadaEm, DateTimeOffset? DesfeitaEm, int ComandaVersao, List<ItemDto> Itens);

internal sealed record ItemCanceladoDto(ItemDto Item, int ComandaVersao);

internal sealed record ItensDaComandaDto(List<ItemDto> Itens, long ConsumoCentavos);

internal sealed record LancarItemRequest(Guid ProdutoId, int Quantidade, string? Observacao);

/// <summary><c>RodadaId</c> is generated by the client (UUID v7): sending it again is a repeat. <c>Versao</c> is the comanda version the client last saw.</summary>
internal sealed record LancarRodadaRequest(Guid RodadaId, int Versao, List<LancarItemRequest> Itens);

internal sealed record DesfazerRodadaRequest(int Versao);

/// <summary><c>Motivo</c> is a code of the standard list (cliente-desistiu, erro-de-lancamento, item-indisponivel, outro); <c>Texto</c> is required with 'outro'.</summary>
internal sealed record CancelarItemRequest(int Versao, string Motivo, string? Texto);

/// <summary><c>VersaoAtual</c> is set when a write carried a stale version.</summary>
internal sealed record ComandaErro(string Codigo, int? VersaoAtual = null);

internal static class ComandasEndpoints
{
    private const long Body = 1024;

    private const long BodyRodada = 32 * 1024;

    public static void MapComandas(this IEndpointRouteBuilder app)
    {
        ArgumentNullException.ThrowIfNull(app);

        app.MapGet("/comandas", async (RequestContextAccessor request, GestaoDeComandas comandas, CancellationToken cancellationToken) =>
                Results.Ok((await comandas.ListarAsync(request, cancellationToken)).Select(Dto).ToList()))
            .WithName("listComandas")
            .RequireSession()
            .RequirePermission(ComandaPermissions.Ver)
            .Produces<List<ComandaDto>>()
            .Produces(StatusCodes.Status401Unauthorized)
            .Produces(StatusCodes.Status403Forbidden);

        app.MapPost("/comandas", async (AbrirComandaRequest body, RequestContextAccessor request, GestaoDeComandas comandas, CancellationToken cancellationToken) =>
            {
                var r = await comandas.AbrirAsync(request, body.Identificacao, body.MesaId, body.Pessoas, cancellationToken);
                return r.Resultado == ResultadoDeComanda.Ok ? Results.Json(Dto(r.Comanda!), statusCode: StatusCodes.Status201Created) : Erro(r);
            })
            .WithName("abrirComanda")
            .RequireSession()
            .WithBodyLimit(Body)
            .RequirePermission(ComandaPermissions.Abrir)
            .Produces<ComandaDto>(StatusCodes.Status201Created)
            .Produces<ComandaErro>(StatusCodes.Status400BadRequest)
            .Produces(StatusCodes.Status401Unauthorized)
            .Produces(StatusCodes.Status403Forbidden)
            .Produces<ComandaErro>(StatusCodes.Status409Conflict);

        app.MapGet("/comandas/{comandaId:guid}/itens", async (Guid comandaId, RequestContextAccessor request, GestaoDeRodadas rodadas, CancellationToken cancellationToken) =>
            {
                var itens = await rodadas.ItensAsync(request, comandaId, cancellationToken);
                return itens is null
                    ? Results.Json(new ComandaErro("nao-encontrada"), statusCode: StatusCodes.Status404NotFound)
                    : Results.Ok(new ItensDaComandaDto(itens.Select(ItemParaDto).ToList(), RegrasDeRodada.Consumo(itens)));
            })
            .WithName("listItensDaComanda")
            .RequireSession()
            .RequirePermission(ComandaPermissions.Ver)
            .Produces<ItensDaComandaDto>()
            .Produces<ComandaErro>(StatusCodes.Status404NotFound)
            .Produces(StatusCodes.Status401Unauthorized)
            .Produces(StatusCodes.Status403Forbidden);

        app.MapPost("/comandas/{comandaId:guid}/rodadas", async (Guid comandaId, LancarRodadaRequest body, RequestContextAccessor request, GestaoDeRodadas rodadas, CancellationToken cancellationToken) =>
            {
                var itens = (body.Itens ?? []).Select(i => new ItemParaLancar(i.ProdutoId, i.Quantidade, i.Observacao)).ToList();
                var r = await rodadas.LancarAsync(request, comandaId, body.RodadaId, body.Versao, itens, cancellationToken);
                return r.Resultado switch
                {
                    ResultadoDeRodada.Ok => Results.Json(RodadaParaDto(r), statusCode: StatusCodes.Status201Created),
                    ResultadoDeRodada.Repetida => Results.Ok(RodadaParaDto(r)),
                    _ => ErroDeEscrita(r),
                };
            })
            .WithName("lancarRodada")
            .RequireSession()
            .WithBodyLimit(BodyRodada)
            .RequirePermission(ComandaPermissions.LancarItem)
            .Produces<RodadaDto>(StatusCodes.Status201Created)
            .Produces<RodadaDto>()
            .Produces<ComandaErro>(StatusCodes.Status400BadRequest)
            .Produces(StatusCodes.Status401Unauthorized)
            .Produces(StatusCodes.Status403Forbidden)
            .Produces<ComandaErro>(StatusCodes.Status404NotFound)
            .Produces<ComandaErro>(StatusCodes.Status409Conflict);

        app.MapPost("/comandas/{comandaId:guid}/rodadas/{rodadaId:guid}/desfazer", async (Guid comandaId, Guid rodadaId, DesfazerRodadaRequest body, RequestContextAccessor request, GestaoDeRodadas rodadas, CancellationToken cancellationToken) =>
            {
                var r = await rodadas.DesfazerAsync(request, comandaId, rodadaId, body.Versao, cancellationToken);
                return r.Resultado == ResultadoDeRodada.Ok ? Results.Ok(RodadaParaDto(r)) : ErroDeEscrita(r);
            })
            .WithName("desfazerRodada")
            .RequireSession()
            .WithBodyLimit(Body)
            .RequirePermission(ComandaPermissions.DesfazerRodada, sensitive: true)
            .Produces<RodadaDto>()
            .Produces<ComandaErro>(StatusCodes.Status400BadRequest)
            .Produces(StatusCodes.Status401Unauthorized)
            .Produces(StatusCodes.Status403Forbidden)
            .Produces<ComandaErro>(StatusCodes.Status404NotFound)
            .Produces<ComandaErro>(StatusCodes.Status409Conflict);

        app.MapPost("/comandas/{comandaId:guid}/itens/{itemId:guid}/cancelar", async (Guid comandaId, Guid itemId, CancelarItemRequest body, RequestContextAccessor request, GestaoDeRodadas rodadas, CancellationToken cancellationToken) =>
            {
                var r = await rodadas.CancelarItemAsync(request, comandaId, itemId, body.Versao, body.Motivo, body.Texto, cancellationToken);
                return r.Resultado == ResultadoDeRodada.Ok ? Results.Ok(new ItemCanceladoDto(ItemParaDto(r.Item!), r.Versao!.Value)) : ErroDeEscrita(r);
            })
            .WithName("cancelarItem")
            .RequireSession()
            .WithBodyLimit(Body)
            .RequirePermission(ComandaPermissions.CancelarItem, sensitive: true)
            .Produces<ItemCanceladoDto>()
            .Produces<ComandaErro>(StatusCodes.Status400BadRequest)
            .Produces(StatusCodes.Status401Unauthorized)
            .Produces(StatusCodes.Status403Forbidden)
            .Produces<ComandaErro>(StatusCodes.Status404NotFound)
            .Produces<ComandaErro>(StatusCodes.Status409Conflict);
    }

    private static ItemDto ItemParaDto(ItemDaComanda i) =>
        new(i.Id, i.RodadaId, i.Posicao, i.ProdutoId, i.ProdutoNome, i.PrecoCentavos, i.Quantidade, i.Observacao, RegrasDeRodada.Palavra(i.Estado), i.MotivoCancelamento, i.CanceladoPor, i.CanceladoEm);

    private static RodadaDto RodadaParaDto(ResultadoDeEscrita r) =>
        new(r.Rodada!.Rodada.Id, r.Rodada.Rodada.ComandaId, r.Rodada.Rodada.EnviadaEm, r.Rodada.Rodada.DesfeitaEm, r.Versao!.Value, r.Rodada.Itens.Select(ItemParaDto).ToList());

    private static IResult ErroDeEscrita(ResultadoDeEscrita r)
    {
        var (status, codigo) = r.Resultado switch
        {
            ResultadoDeRodada.ComandaNaoEncontrada or ResultadoDeRodada.RodadaNaoEncontrada or ResultadoDeRodada.ItemNaoEncontrado => (StatusCodes.Status404NotFound, "nao-encontrada"),
            ResultadoDeRodada.ComandaNaoAberta => (StatusCodes.Status409Conflict, "comanda-nao-aberta"),
            ResultadoDeRodada.ProdutoInativo => (StatusCodes.Status409Conflict, "produto-inativo"),
            ResultadoDeRodada.VersaoDesatualizada => (StatusCodes.Status409Conflict, "versao-desatualizada"),
            ResultadoDeRodada.SomenteQuemEnviou => (StatusCodes.Status409Conflict, "somente-quem-enviou"),
            ResultadoDeRodada.JanelaExpirada => (StatusCodes.Status409Conflict, "janela-expirada"),
            ResultadoDeRodada.RodadaJaDesfeita => (StatusCodes.Status409Conflict, "rodada-ja-desfeita"),
            ResultadoDeRodada.RodadaComItemCancelado => (StatusCodes.Status409Conflict, "rodada-com-item-cancelado"),
            ResultadoDeRodada.ItemJaCancelado => (StatusCodes.Status409Conflict, "item-ja-cancelado"),
            _ => (StatusCodes.Status400BadRequest, "invalido"),
        };
        return Results.Json(new ComandaErro(codigo, r.VersaoAtual), statusCode: status);
    }

    private static ComandaDto Dto(Comanda c) =>
        new(c.Id, c.UnidadeId, c.Numero, RegrasDeComanda.NumeroDeExibicao(c.Numero), c.Identificacao, c.MesaId, c.Canal, c.GarcomId, c.Pessoas, RegrasDeComanda.Palavra(c.Estado), c.TaxaServicoPercentual, c.TaxaServicoRemovida, c.Versao, c.AbertaEm);

    private static IResult Erro(ResultadoDeAbrir r) => r.Resultado switch
    {
        ResultadoDeComanda.MesasDesligadas => Results.Json(new ComandaErro("mesas-desligadas"), statusCode: StatusCodes.Status409Conflict),
        ResultadoDeComanda.VersaoDesatualizada => Results.Json(new ComandaErro("versao-desatualizada", r.VersaoAtual), statusCode: StatusCodes.Status409Conflict),
        _ => Results.Json(new ComandaErro("invalido"), statusCode: StatusCodes.Status400BadRequest),
    };
}
