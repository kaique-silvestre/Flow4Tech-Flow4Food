using Flow4Tech.Comandas.Application;
using Flow4Tech.Comandas.Domain;

namespace Flow4Tech.Api;

/// <summary>
/// How to split the bill. <c>Modo</c> is <c>iguais</c> (<c>Partes</c>, 2 to 50), <c>assento</c> (the seats of the launched items; items without a seat are shared), <c>item</c> (<c>Grupos</c>: each launched item in
/// exactly one group), <c>valores</c> (<c>Valores</c> in cents, adding up to the bill) or <c>percentual</c> (<c>Percentuais</c> with two decimals, adding up to 100). <c>GorjetaCentavos</c> is an optional tip
/// (0 or more) shared by the same rule; it stays outside the bill.
/// </summary>
internal sealed record PedidoDeDivisaoRequest(string Modo, int? Partes, List<List<Guid>>? Grupos, List<long>? Valores, List<decimal>? Percentuais, long? GorjetaCentavos);

/// <summary>Records a split. <c>DivisaoId</c> is generated by the client (UUID v7): repeating it answers the recorded split. <c>Versao</c> is the comanda version the screen saw.</summary>
internal sealed record DividirContaRequest(Guid DivisaoId, int Versao, PedidoDeDivisaoRequest Pedido);

/// <summary>A part of a split. <c>TotalCentavos</c> is what it owes of the bill (<c>ConsumoCentavos</c> after discounts plus <c>TaxaServicoCentavos</c>); <c>GorjetaCentavos</c> is its share of the tip; <c>APagarCentavos</c> is both.</summary>
internal sealed record ParteDaDivisaoDto(int Numero, int? Assento, List<Guid> ItemIds, long ConsumoCentavos, long TaxaServicoCentavos, long TotalCentavos, long GorjetaCentavos, long APagarCentavos);

/// <summary>What a request would give: nothing is written. <c>ComandaVersao</c> is the version the preview was computed against.</summary>
internal sealed record PreviaDaDivisaoDto(string Modo, int ComandaVersao, long TotalCentavos, long TaxaServicoCentavos, long GorjetaCentavos, List<ParteDaDivisaoDto> Partes);

/// <summary>A recorded split. <c>ComandaVersao</c> is the comanda version it produced; <c>Vigente</c> is false once the comanda changed after it.</summary>
internal sealed record DivisaoDto(Guid Id, Guid ComandaId, string Modo, int ComandaVersao, bool Vigente, long TotalCentavos, long TaxaServicoCentavos, long GorjetaCentavos, DateTimeOffset CriadoEm, List<ParteDaDivisaoDto> Partes);

/// <summary>Codes: <c>invalido</c>, <c>soma-diferente</c>, <c>itens-fora-das-partes</c> (400), <c>nao-encontrada</c>, <c>sem-divisao</c> (404), <c>comanda-nao-aberta</c>, <c>versao-desatualizada</c>, <c>valor-ja-recebido</c>, <c>id-em-uso</c>, <c>divisao-invalida</c> (409).</summary>
internal sealed record DivisaoErro(string Codigo, int? VersaoAtual = null);

internal static class ComandasDivisaoEndpoints
{
    private const long Body = 16384;

    public static void MapDivisaoDaConta(this IEndpointRouteBuilder app)
    {
        ArgumentNullException.ThrowIfNull(app);

        app.MapPost("/comandas/{comandaId:guid}/divisao/previa", async (Guid comandaId, PedidoDeDivisaoRequest body, RequestContextAccessor request, GestaoDaDivisaoDaConta gestao, CancellationToken cancellationToken) =>
            {
                var pedido = Pedido(body);
                if (pedido is null)
                {
                    return Erro(new ResultadoDaDivisaoDaContaCompleto(ResultadoDaDivisaoDaConta.Invalido));
                }

                var r = await gestao.PreviaAsync(request, comandaId, pedido, cancellationToken);
                return r.Resultado == ResultadoDaDivisaoDaConta.Ok
                    ? Results.Ok(new PreviaDaDivisaoDto(RegrasDeDivisao.Palavra(pedido.Modo), r.ComandaVersao!.Value, r.Conta!.TotalCentavos, r.Conta.TaxaServicoCentavos, pedido.GorjetaCentavos, Partes(r.Partes!)))
                    : Erro(r);
            })
            .WithName("previaDivisaoDaConta")
            .RequireSession()
            .WithBodyLimit(Body)
            .RequirePermission(ComandaPermissions.Dividir)
            .Produces<PreviaDaDivisaoDto>()
            .Produces<DivisaoErro>(StatusCodes.Status400BadRequest)
            .Produces(StatusCodes.Status401Unauthorized)
            .Produces(StatusCodes.Status403Forbidden)
            .Produces<DivisaoErro>(StatusCodes.Status404NotFound)
            .Produces<DivisaoErro>(StatusCodes.Status409Conflict);

        app.MapPost("/comandas/{comandaId:guid}/divisao", async (Guid comandaId, DividirContaRequest body, RequestContextAccessor request, GestaoDaDivisaoDaConta gestao, CancellationToken cancellationToken) =>
            {
                var pedido = Pedido(body.Pedido);
                if (pedido is null)
                {
                    return Erro(new ResultadoDaDivisaoDaContaCompleto(ResultadoDaDivisaoDaConta.Invalido));
                }

                var r = await gestao.DividirAsync(request, comandaId, body.DivisaoId, body.Versao, pedido, cancellationToken);
                return r.Resultado == ResultadoDaDivisaoDaConta.Ok
                    ? Results.Json(Dto(r.Divisao!, true), statusCode: r.Repetida ? StatusCodes.Status200OK : StatusCodes.Status201Created)
                    : Erro(r);
            })
            .WithName("dividirContaDaComanda")
            .RequireSession()
            .WithBodyLimit(Body)
            .RequirePermission(ComandaPermissions.Dividir)
            .Produces<DivisaoDto>()
            .Produces<DivisaoDto>(StatusCodes.Status201Created)
            .Produces<DivisaoErro>(StatusCodes.Status400BadRequest)
            .Produces(StatusCodes.Status401Unauthorized)
            .Produces(StatusCodes.Status403Forbidden)
            .Produces<DivisaoErro>(StatusCodes.Status404NotFound)
            .Produces<DivisaoErro>(StatusCodes.Status409Conflict);

        app.MapGet("/comandas/{comandaId:guid}/divisao", async (Guid comandaId, RequestContextAccessor request, GestaoDaDivisaoDaConta gestao, CancellationToken cancellationToken) =>
            {
                var r = await gestao.VigenteAsync(request, comandaId, cancellationToken);
                return r.Resultado == ResultadoDaDivisaoDaConta.Ok ? Results.Ok(Dto(r.Divisao!, true)) : Erro(r);
            })
            .WithName("getDivisaoDaComanda")
            .RequireSession()
            .RequirePermission(ComandaPermissions.Dividir)
            .Produces<DivisaoDto>()
            .Produces(StatusCodes.Status401Unauthorized)
            .Produces(StatusCodes.Status403Forbidden)
            .Produces<DivisaoErro>(StatusCodes.Status404NotFound)
            .Produces<DivisaoErro>(StatusCodes.Status409Conflict);
    }

    private static PedidoDeDivisao? Pedido(PedidoDeDivisaoRequest? body) =>
        body is not null && RegrasDeDivisao.TentarModo(body.Modo, out var modo)
            ? new PedidoDeDivisao(modo, body.Partes, body.Grupos?.Select(g => (IReadOnlyList<Guid>)(g ?? [])).ToList(), body.Valores, body.Percentuais, body.GorjetaCentavos ?? 0)
            : null;

    private static List<ParteDaDivisaoDto> Partes(IReadOnlyList<ParteDaDivisao> partes) =>
        partes.Select(p => new ParteDaDivisaoDto(p.Numero, p.Assento, [.. p.ItemIds], p.ConsumoCentavos, p.TaxaServicoCentavos, p.TotalCentavos, p.GorjetaCentavos, p.APagarCentavos)).ToList();

    private static DivisaoDto Dto(DivisaoGravada d, bool vigente) =>
        new(d.Id, d.ComandaId, RegrasDeDivisao.Palavra(d.Modo), d.ComandaVersao, vigente, d.TotalCentavos, d.TaxaServicoCentavos, d.GorjetaCentavos, d.CriadoEm, Partes(d.Partes));

    private static IResult Erro(ResultadoDaDivisaoDaContaCompleto r)
    {
        var (status, codigo) = r.Resultado switch
        {
            ResultadoDaDivisaoDaConta.SomaDiferente => (StatusCodes.Status400BadRequest, "soma-diferente"),
            ResultadoDaDivisaoDaConta.ItensForaDasPartes => (StatusCodes.Status400BadRequest, "itens-fora-das-partes"),
            ResultadoDaDivisaoDaConta.ComandaNaoEncontrada => (StatusCodes.Status404NotFound, "nao-encontrada"),
            ResultadoDaDivisaoDaConta.SemDivisao => (StatusCodes.Status404NotFound, "sem-divisao"),
            ResultadoDaDivisaoDaConta.ComandaNaoAberta => (StatusCodes.Status409Conflict, "comanda-nao-aberta"),
            ResultadoDaDivisaoDaConta.VersaoDesatualizada => (StatusCodes.Status409Conflict, "versao-desatualizada"),
            ResultadoDaDivisaoDaConta.ValorJaRecebido => (StatusCodes.Status409Conflict, "valor-ja-recebido"),
            ResultadoDaDivisaoDaConta.IdEmUso => (StatusCodes.Status409Conflict, "id-em-uso"),
            ResultadoDaDivisaoDaConta.DivisaoInvalida => (StatusCodes.Status409Conflict, "divisao-invalida"),
            _ => (StatusCodes.Status400BadRequest, "invalido"),
        };
        return Results.Json(new DivisaoErro(codigo, r.VersaoAtual), statusCode: status);
    }
}
