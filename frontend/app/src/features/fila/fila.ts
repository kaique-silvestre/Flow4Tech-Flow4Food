import { useSyncExternalStore } from "react";
import { api, contaDaSessao, lerSessao } from "../sessao/sessao";

/**
 * The pending-actions queue (ADR-015): a write that cannot go now (no signal, a server hiccup) waits here, visible, and is sent in order when it can. The id of every action is made on the
 * client (UUID v7) and is the id the server keeps the round under, so sending it twice, from here or from a lost answer, is one round. The queue lives in the browser's storage so a reload does
 * not lose it, and an action only goes out for the account that queued it.
 */
export interface ItemDaFila {
  produtoId: string;
  quantidade: number;
  observacao: string | null;
}

export interface AcaoDaFilaDeRodada {
  /** The round id, generated by the client. */
  id: string;
  tipo: "rodada";
  contaId: string;
  comandaId: string;
  titulo: string;
  detalhe: string;
  itens: ItemDaFila[];
  criadoEm: number;
  tentativas: number;
  /** Do not try before this instant (ms since epoch): the back-off. */
  proxima: number;
  estado: "pendente" | "enviando" | "falhou";
  /** Why it did not go (state `falhou`) or what the last attempt met. */
  motivo: string | null;
}

export interface MensagemDaFila {
  texto: string;
  /** The comanda changed on another device while the action waited. */
  conflito: boolean;
}

const CHAVE = "f4.fila.v1";
const ATRASO_INICIAL_MS = 2000;
const ATRASO_MAXIMO_MS = 30_000;
const TENTATIVAS_DE_VERSAO = 3;

let acoes: AcaoDaFilaDeRodada[] = ler();
let mensagem: MensagemDaFila | null = null;
let rodando = false;
let reservado: (() => void) | null = null;
const ouvintes = new Set<() => void>();
let aoConcluir: (acao: AcaoDaFilaDeRodada) => void = () => undefined;

function ler(): AcaoDaFilaDeRodada[] {
  try {
    const bruto = window.localStorage.getItem(CHAVE);
    if (!bruto) {
      return [];
    }

    const lista = JSON.parse(bruto) as unknown;
    return Array.isArray(lista)
      ? lista
          .filter((a): a is AcaoDaFilaDeRodada => typeof a === "object" && a !== null && (a as { tipo?: unknown }).tipo === "rodada")
          // An action that was in flight when the page closed is simply pending again (the server keeps it idempotent by id).
          .map((a) => ({ ...a, estado: a.estado === "enviando" ? "pendente" : a.estado }))
      : [];
  } catch {
    return [];
  }
}

function gravar() {
  try {
    window.localStorage.setItem(CHAVE, JSON.stringify(acoes));
  } catch {
    // Private mode or a full disk: the queue still works for this page.
  }
}

function mudou() {
  gravar();
  for (const ouvinte of ouvintes) {
    ouvinte();
  }
}

function atualizar(id: string, mudancas: Partial<AcaoDaFilaDeRodada>) {
  acoes = acoes.map((a) => (a.id === id ? { ...a, ...mudancas } : a));
  mudou();
}

function dizer(m: MensagemDaFila) {
  mensagem = m;
  mudou();
  window.setTimeout(() => {
    if (mensagem === m) {
      mensagem = null;
      mudou();
    }
  }, 6000);
}

export function lerFila(): readonly AcaoDaFilaDeRodada[] {
  return acoes;
}

export function enfileirarRodada(entrada: { rodadaId: string; comandaId: string; itens: ItemDaFila[]; titulo: string; detalhe: string }): void {
  const contaId = contaDaSessao();
  if (contaId === null || acoes.some((a) => a.id === entrada.rodadaId)) {
    return;
  }

  acoes = [...acoes, { id: entrada.rodadaId, tipo: "rodada", contaId, comandaId: entrada.comandaId, titulo: entrada.titulo, detalhe: entrada.detalhe, itens: entrada.itens, criadoEm: Date.now(), tentativas: 0, proxima: 0, estado: "pendente", motivo: null }];
  mudou();
  void processar();
}

export function removerAcao(id: string): void {
  acoes = acoes.filter((a) => a.id !== id);
  mudou();
}

/** Skip the wait of the back-off for one action and try it now. */
export function tentarAgora(id: string): void {
  atualizar(id, { proxima: 0, estado: "pendente" });
  void processar();
}

/** Signing out forgets what was waiting: the next person on the device never sends it. */
export function limparFila(): void {
  acoes = [];
  mensagem = null;
  mudou();
}

export function useFila(): { acoes: readonly AcaoDaFilaDeRodada[]; mensagem: MensagemDaFila | null } {
  const snapshot = useSyncExternalStore(
    (ouvinte) => {
      ouvintes.add(ouvinte);
      return () => ouvintes.delete(ouvinte);
    },
    () => acoes,
  );
  const msg = useSyncExternalStore(
    (ouvinte) => {
      ouvintes.add(ouvinte);
      return () => ouvintes.delete(ouvinte);
    },
    () => mensagem,
  );
  return { acoes: snapshot, mensagem: msg };
}

type Resultado = { tipo: "ok"; conflito: boolean } | { tipo: "adiar"; motivo: string } | { tipo: "falhou"; motivo: string } | { tipo: "sessao" };

async function enviar(acao: AcaoDaFilaDeRodada): Promise<Resultado> {
  let conflito = false;
  try {
    // The version is read at send time, not when the action was queued: it may have waited a long while and another device may have written since.
    const lida = await api.GET("/comandas/{comandaId}/conta", { params: { path: { comandaId: acao.comandaId } } });
    if (lida.response.status === 401) {
      return { tipo: "sessao" };
    }

    if (lida.response.status === 403 || lida.response.status === 404) {
      return { tipo: "falhou", motivo: "A comanda não está mais disponível para você." };
    }

    if (!lida.data) {
      return { tipo: "adiar", motivo: "Aguardando o servidor" };
    }

    let versao = Number(lida.data.versao);
    for (let tentativa = 0; tentativa < TENTATIVAS_DE_VERSAO; tentativa += 1) {
      const { data, response, error } = await api.POST("/comandas/{comandaId}/rodadas", {
        params: { path: { comandaId: acao.comandaId } },
        body: { rodadaId: acao.id, versao, itens: acao.itens.map((i) => ({ produtoId: i.produtoId, quantidade: i.quantidade, observacao: i.observacao })) },
      });
      if (data) {
        return { tipo: "ok", conflito };
      }

      const codigo = (error as { codigo?: string; versaoAtual?: number | null } | undefined)?.codigo;
      if (response.status === 401) {
        return { tipo: "sessao" };
      }

      if (response.status === 409 && codigo === "versao-desatualizada") {
        // Another device changed the comanda: adopt the version the server names and send the same round again (the items were already chosen).
        conflito = true;
        const atual = (error as { versaoAtual?: number | null }).versaoAtual;
        versao = typeof atual === "number" ? atual : versao + 1;
        continue;
      }

      if (response.status === 409 && codigo === "comanda-nao-aberta") {
        return { tipo: "falhou", motivo: "A comanda não está mais aberta." };
      }

      if (response.status === 409 && codigo === "produto-inativo") {
        return { tipo: "falhou", motivo: "Um item não está mais disponível." };
      }

      if (response.status === 403) {
        return { tipo: "falhou", motivo: "Você não tem permissão para lançar itens." };
      }

      if (response.status === 404) {
        return { tipo: "falhou", motivo: "A comanda não está mais disponível para você." };
      }

      if (response.status === 400) {
        return { tipo: "falhou", motivo: "A rodada não foi aceita. Confira os itens." };
      }

      return { tipo: "adiar", motivo: "Aguardando o servidor" };
    }

    return { tipo: "adiar", motivo: "A comanda está mudando. Tentando de novo" };
  } catch {
    return { tipo: "adiar", motivo: "Aguardando conexão" };
  }
}

function agendar() {
  const proxima = acoes.filter((a) => a.estado === "pendente").map((a) => a.proxima).sort((x, y) => x - y)[0];
  if (proxima === undefined) {
    return;
  }

  const espera = Math.max(250, proxima - Date.now());
  if (reservado) {
    return;
  }

  const timer = window.setTimeout(() => {
    reservado = null;
    void processar();
  }, espera);
  reservado = () => window.clearTimeout(timer);
}

/**
 * Sends what is due, in order. One at a time (so the refresh of the session, which the fetch layer shares, is never raced by several queued requests). A pending action that must wait
 * (back-off, no signal) holds the ones behind it, so rounds go in the order they were made; an action that cannot go at all (`falhou`) is shown and does not block the rest.
 */
export async function processar(): Promise<void> {
  if (rodando) {
    return;
  }

  rodando = true;
  try {
    for (;;) {
      const sessao = lerSessao();
      const conta = contaDaSessao();
      const alvo = acoes.find((a) => a.estado !== "falhou" && a.contaId === conta);
      if (sessao.status !== "ativa" || !alvo || alvo.proxima > Date.now() || !navigator.onLine) {
        break;
      }

      atualizar(alvo.id, { estado: "enviando" });
      const r = await enviar(alvo);
      if (r.tipo === "ok") {
        acoes = acoes.filter((a) => a.id !== alvo.id);
        mudou();
        dizer({ texto: r.conflito ? "Esta comanda foi alterada em outro aparelho. Atualizamos e enviamos a rodada." : `${alvo.titulo} enviada.`, conflito: r.conflito });
        aoConcluir(alvo);
      } else if (r.tipo === "falhou") {
        atualizar(alvo.id, { estado: "falhou", motivo: r.motivo });
      } else if (r.tipo === "sessao") {
        atualizar(alvo.id, { estado: "pendente", motivo: "Entre de novo para enviar" });
        break;
      } else {
        const tentativas = alvo.tentativas + 1;
        atualizar(alvo.id, { estado: "pendente", tentativas, motivo: r.motivo, proxima: Date.now() + Math.min(ATRASO_MAXIMO_MS, ATRASO_INICIAL_MS * 2 ** (tentativas - 1)) });
        break;
      }
    }
  } finally {
    rodando = false;
    agendar();
  }
}

/** Wires the queue to the page: sends when the signal returns, on a slow tick, and tells the app when an action was accepted (to refresh what it shows). Returns the cleanup. */
export function iniciarProcessador(concluiu: (acao: AcaoDaFilaDeRodada) => void): () => void {
  aoConcluir = concluiu;
  const voltou = () => void processar();
  window.addEventListener("online", voltou);
  const tick = window.setInterval(() => void processar(), 3000);
  void processar();
  return () => {
    window.removeEventListener("online", voltou);
    window.clearInterval(tick);
    aoConcluir = () => undefined;
  };
}

/** Test seam: an empty, idle queue. */
export function reiniciarFilaParaTestes() {
  reservado?.();
  reservado = null;
  acoes = [];
  mensagem = null;
  rodando = false;
  aoConcluir = () => undefined;
  try {
    window.localStorage.removeItem(CHAVE);
  } catch {
    // Nothing to forget.
  }

  for (const ouvinte of ouvintes) {
    ouvinte();
  }
}

/** Test seam: read the stored queue again, as a page reload does. */
export function recarregarFilaParaTestes() {
  acoes = ler();
  for (const ouvinte of ouvintes) {
    ouvinte();
  }
}
