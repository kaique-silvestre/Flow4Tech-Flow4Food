/**
 * The pending-actions queue (ADR-015): a write that cannot go now (no signal, a server hiccup) waits here, visible, and is sent in order when it can. The id of every action is made on the
 * client (UUID v7) and is the id the server keeps the round under, so sending it twice, from here or from a lost answer, is one round. The queue lives in the browser's storage so a reload does
 * not lose it, and an action only goes out for the account that queued it.
 */
export interface ItemDaFila {
  produtoId: string;
  quantidade: number;
  observacao: string | null;
  /** Add-ons by id (the server recomputes name and price). Absent in actions queued before add-ons existed. */
  opcaoIds?: string[];
}

/** What an `edicao` action changes on the comanda (the version is read at send time, never stored). */
export type EdicaoDaFila =
  | { tipo: "item"; itemId: string; quantidade: number; observacao: string | null }
  | { tipo: "nome"; identificacao: string }
  | { tipo: "garcom"; garcomId: string }
  | { tipo: "dados"; pessoas: number | null; observacao: string | null };

export interface AcaoDaFilaDeRodada {
  /** The round id, generated by the client. */
  id: string;
  tipo: "rodada" | "pagamento" | "cancelamento" | "repeticao" | "edicao";
  contaId: string;
  comandaId: string;
  titulo: string;
  detalhe: string;
  itens: ItemDaFila[];
  /** Cash received (a `pagamento` action): the id of the action is the payment id the server keeps it under. */
  recebidoCentavos?: number;
  /** A `cancelamento` action: the item to cancel, the reason code and the free text. */
  itemId?: string;
  codigoDoMotivo?: string;
  textoDoMotivo?: string | null;
  /** An `edicao` action: what to change on the comanda. */
  edicao?: EdicaoDaFila;
  criadoEm: number;
  tentativas: number;
  /** Do not try before this instant (ms since epoch): the back-off. */
  proxima: number;
  estado: "pendente" | "enviando" | "falhou";
  /** Why it did not go (state `falhou`) or what the last attempt met. */
  motivo: string | null;
  /** A `pagamento` whose money the server already holds and only the close is missing (it stops retrying after a few attempts and shows as stuck). */
  pago?: boolean;
}

export interface MensagemDaFila {
  texto: string;
  /** The comanda changed on another device while the action waited. */
  conflito: boolean;
}

const CHAVE = "f4.fila.v1";
const ATRASO_INICIAL_MS = 2000;
const ATRASO_MAXIMO_MS = 30_000;
const TENTATIVAS_DE_VERSAO = 3;
/** How many times a close that follows a recorded payment is tried before the action is shown as stuck. */
const TENTATIVAS_DE_FECHAR = 5;

let acoes: AcaoDaFilaDeRodada[] = ler();
/** Ids this page finished or removed: a merge with the storage (another tab) must not bring them back. */
const retirados = new Set<string>();
/** The same ids in the storage, so another tab also knows an action was finished or removed (a tab holding it must not write it back). Bounded. */
const CHAVE_RETIRADOS = "f4.fila.v1.retirados";
const LIMITE_DE_RETIRADOS = 200;

function lerRetiradosGuardados(): string[] {
  try {
    const lista = JSON.parse(window.localStorage.getItem(CHAVE_RETIRADOS) ?? "[]") as unknown;
    return Array.isArray(lista) ? lista.filter((x): x is string => typeof x === "string") : [];
  } catch {
    return [];
  }
}

function retirar(id: string) {
  retirados.add(id);
  try {
    const guardados = lerRetiradosGuardados().filter((x) => x !== id);
    window.localStorage.setItem(CHAVE_RETIRADOS, JSON.stringify([...guardados, id].slice(-LIMITE_DE_RETIRADOS)));
  } catch {
    // The local set still protects this page.
  }
}

function foiRetirado(id: string): boolean {
  return retirados.has(id) || lerRetiradosGuardados().includes(id);
}
let mensagem: MensagemDaFila | null = null;
let rodando = false;
let reservado: (() => void) | null = null;
const ouvintes = new Set<() => void>();
let aoConcluir: (acao: AcaoDaFilaDeRodada) => void = () => undefined;

function ler(): AcaoDaFilaDeRodada[] {
  try {
    const bruto = window.localStorage.getItem(CHAVE);
    if (!bruto) {
      return [];
    }

    const lista = JSON.parse(bruto) as unknown;
    return Array.isArray(lista)
      ? lista
          .filter(
            (a): a is AcaoDaFilaDeRodada =>
              typeof a === "object" &&
              a !== null &&
              ["rodada", "pagamento", "cancelamento", "repeticao", "edicao"].includes(
                (a as { tipo?: string }).tipo ?? "",
              ),
          )
          // An action that was in flight when the page closed is simply pending again (the server keeps it idempotent by id).
          .map((a) => ({ ...a, estado: a.estado === "enviando" ? "pendente" : a.estado }))
      : [];
  } catch {
    return [];
  }
}

/** Entries another tab wrote that this page does not hold are kept (merge by id), so two tabs of the same account never erase each other's queued actions. */
function incorporarDoArmazenamento() {
  // What another tab finished or removed is gone here too (unless this page is sending it right now).
  const sobraram = acoes.filter((a) => a.estado === "enviando" || !foiRetirado(a.id));
  const mudouAqui = sobraram.length !== acoes.length;
  acoes = sobraram;
  const guardadas = ler().filter((g) => !foiRetirado(g.id) && !acoes.some((a) => a.id === g.id));
  if (guardadas.length > 0 || mudouAqui) {
    acoes = [...acoes, ...guardadas].sort((x, y) => x.criadoEm - y.criadoEm);
  }
}

function gravar() {
  try {
    incorporarDoArmazenamento();
    window.localStorage.setItem(CHAVE, JSON.stringify(acoes));
  } catch {
    // Private mode or a full disk: the queue still works for this page.
  }
}

function mudou() {
  gravar();
  for (const ouvinte of ouvintes) {
    ouvinte();
  }
}

function atualizar(id: string, mudancas: Partial<AcaoDaFilaDeRodada>) {
  acoes = acoes.map((a) => (a.id === id ? { ...a, ...mudancas } : a));
  mudou();
}

function dizer(m: MensagemDaFila, duracaoMs = 6000) {
  mensagem = m;
  mudou();
  window.setTimeout(() => {
    if (mensagem === m) {
      mensagem = null;
      mudou();
    }
  }, duracaoMs);
}

