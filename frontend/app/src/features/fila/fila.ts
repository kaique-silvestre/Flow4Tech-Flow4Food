/** Removes an action from the queue. One that is being sent right now is refused (the server may already be taking it). Returns whether it was removed. */
export function removerAcao(id: string): boolean {
  const alvo = acoes.find((a) => a.id === id);
  if (!alvo || alvo.estado === "enviando") {
    return false;
  }

  retirar(id);
  acoes = acoes.filter((a) => a.id !== id);
  mudou();
  return true;
}

/** Whether the queue still holds something for this comanda that has not failed for good: a new write for it must go behind that, never ahead. */
export function temAcaoViva(comandaId: string): boolean {
  return acoes.some((a) => a.comandaId === comandaId && a.estado !== "falhou");
}

/** The cash waiting in the queue for this comanda (payments not failed for good): the balance the close sheet may offer is the server's minus this. */
export function recebidoNaFila(comandaId: string): number {
  return acoes
    .filter((a) => a.tipo === "pagamento" && a.comandaId === comandaId && a.estado !== "falhou" && !a.pago)
    .reduce((soma, a) => soma + (a.recebidoCentavos ?? 0), 0);
}

/** Whether a payment of this comanda waits in the queue (pending, sending or paid-but-not-closed). */
export function pagamentoNaFila(comandaId: string): boolean {
  return acoes.some((a) => a.tipo === "pagamento" && a.comandaId === comandaId && a.estado !== "falhou");
}

/** Skip the wait of the back-off for one action and try it now. */
export function tentarAgora(id: string): void {
  atualizar(id, { proxima: 0, estado: "pendente", tentativas: 0 });
  void processar();
}

/** Signing out forgets what was waiting: the next person on the device never sends it. */
export function limparFila(): void {
  for (const a of acoes) {
    retirar(a.id);
  }

  acoes = [];
  mensagem = null;
  try {
    window.localStorage.removeItem(CHAVE);
  } catch {
    // Nothing to forget.
  }

  for (const ouvinte of ouvintes) {
    ouvinte();
  }
}

/** Drops what another account queued on this device: it is never sent by, nor shown to, the person now signed in. */
function descartarDeOutrasContas() {
  const conta = contaDaSessao();
  if (conta === null || acoes.every((a) => a.contaId === conta)) {
    return;
  }

  for (const a of acoes) {
    if (a.contaId !== conta) {
      retirar(a.id);
    }
  }

  acoes = acoes.filter((a) => a.contaId === conta);
  mudou();
}

/** The session ended: what was still waiting is dropped, and the sign-in screen says how many actions that was. */
function descartarAoEncerrar() {
  const quantas = acoes.length;
  limparFila();
  if (quantas > 0) {
    registrarDescarte(quantas);
  }
}

aoEncerrarSessao(descartarAoEncerrar);
aoAtivarSessao(descartarDeOutrasContas);

